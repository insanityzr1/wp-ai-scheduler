// Function to fetch Wikipedia extract with timeout
function fetch_wiki_text($wiki_slug, $fallback_html) {
	$url = 'https://en.wikipedia.org/api/rest_v1/page/summary/' . urlencode($wiki_slug);
	$ctx = stream_context_create(array(
		'http' => array(
			'timeout' => 4,
			'header'  => "User-Agent: AIPS-LinkGraphSeeder/1.0 (WordPress Dev Test)\r\n"
		)
	));

	$json = @file_get_contents($url, false, $ctx);
	if ($json) {
		$data = json_decode($json, true);
		if (!empty($data['extract'])) {
			return '<p>' . esc_html($data['extract']) . '</p>' . $fallback_html;
		}
	}

	return $fallback_html;
}

