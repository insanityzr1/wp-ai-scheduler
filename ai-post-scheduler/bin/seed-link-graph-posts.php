	echo "  - Processing: {$t['title']}... ";
	
	// Check if post with this slug already exists
	$existing = get_page_by_path($t['slug'], OBJECT, 'post');
	$post_content = fetch_wiki_text($t['wiki'], $t['fallback']);

	$post_data = array(
		'post_title'   => $t['title'],
		'post_name'    => $t['slug'],
		'post_content' => $post_content,
		'post_status'  => 'publish',
		'post_type'    => 'post',
		'post_author'  => 1,
	);

	if ($existing) {
		$post_data['ID'] = $existing->ID;
		$post_id = wp_update_post($post_data);
		echo "[Updated: #$post_id]\n";
	} else {
		$post_id = wp_insert_post($post_data);
		echo "[Created: #$post_id]\n";
	}

	$created_post_ids[$t['slug']] = (int) $post_id;
}

echo "\nStep 2: Injecting Topological Cross-Links...\n";
foreach ($topics as $t) {
	$source_id = $created_post_ids[$t['slug']] ?? 0;
	if (!$source_id || empty($t['links_to'])) {
		continue;
	}

	$post = get_post($source_id);
	$content = $post->post_content;
	$links_html = "\n\n<h3>Related Topological Readings</h3>\n<ul>\n";

	foreach ($t['links_to'] as $target_slug) {
		$target_id = $created_post_ids[$target_slug] ?? 0;
		if (!$target_id) {
			continue;
		}
		$target_title = get_the_title($target_id);
		$target_url   = get_permalink($target_id);
		$links_html  .= "<li>Recommended exploration: <a href=\"{$target_url}\">{$target_title}</a></li>\n";
	}
	$links_html .= "</ul>\n";

	// Append links if not already present
	if (strpos($content, 'Related Topological Readings') === false) {
		$content .= $links_html;
		wp_update_post(array(
			'ID'           => $source_id,
			'post_content' => $content,
		));
	}
	echo "  - Injected outgoing links for #$source_id ({$t['slug']})\n";
}

